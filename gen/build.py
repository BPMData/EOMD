"""gen/build.py: bundle the cartridges and build one self-contained, offline player.

Run in Thonny (or `python3 gen/build.py`). Settings are below; nothing else needs editing.
  1. Reads every carts/*.json (checks it parses and uses known layers) and writes carts/_bundle.js,
     so gen/player.html works straight from the folder (double-click it).
  2. Writes dist/<OUT_NAME>: player.html with every script inlined (+ optional embedded fonts and audio).
     That single file is the deliverable: no internet, no other files.
Cartridges in carts/private/ build the same way; keep anything you can't publish there (e.g. a script
transcribed from a commercial record) and leave that folder out of a public repo.
"""
import base64, json, os, re, sys

# ---------------- settings ----------------
GEN_DIR      = os.path.dirname(os.path.abspath(__file__))
OUT_DIR      = os.path.join(GEN_DIR, 'dist')
OUT_NAME     = 'gen-player.html'
ONLY_CART    = ''          # '' = the full player; a cartridge name (e.g. 'pltw-cse') = a STANDALONE player:
                           # dist/<name>.html with only that cartridge, opening straight into it, page title from it
ONLY_CARTS   = []          # [] = all cartridges; or e.g. ['reel', 'depth-morph'] (ignored when ONLY_CART is set)
DEFAULT_CART = 'reel'      # opens first (the viewer's last pick wins after that)
PAGE_TITLE   = 'Gen Player'
FONT_FILE    = ''          # optional OFL font for the HUD (.woff2 / .woff / .ttf / .otf), e.g. '/Users/you/fonts/SourceCodePro-Medium.ttf'
                           # empty = the viewer's system monospace (Menlo / Consolas), still fully offline
DISPLAY_FONT = os.path.join(GEN_DIR, 'fonts', 'Montserrat-Bold.ttf')   # optional OFL display font for kinetic type and halftone words (font name GenDisplay),
                           # e.g. '/Users/you/fonts/BagelFatOne-Regular.ttf'; empty = Arial Black / Impact
AUDIO_DIR    = os.path.join(GEN_DIR, 'audio')   # where a cartridge's "audio" file is looked up
EMBED_AUDIO  = True        # put each used track inside the built file (a 4 MB MP3 adds ~5.5 MB)
# ------------------------------------------

def main(only_cart=None, out_path=None):
    """Build. only_cart / out_path override ONLY_CART / OUT_DIR+name (tools/gen_export.py calls it this way). Returns the path written."""
    only_cart = ONLY_CART if only_cart is None else only_cart
    carts_dir = os.path.join(GEN_DIR, 'carts')
    layer_names = set()
    for f in os.listdir(os.path.join(GEN_DIR, 'layers')):
        if f.endswith('.js'):
            src = open(os.path.join(GEN_DIR, 'layers', f), encoding='utf-8').read()
            layer_names.update(re.findall(r'G\.layers\.(\w+)\s*=', src))

    carts, problems = {}, []
    files = [(f, os.path.join(carts_dir, f)) for f in sorted(os.listdir(carts_dir))]
    priv = os.path.join(carts_dir, 'private')
    if os.path.isdir(priv):
        files += [('private/' + f, os.path.join(priv, f)) for f in sorted(os.listdir(priv))]
    for f, fpath in files:
        if not f.endswith('.json'):
            continue
        name = os.path.basename(f)[:-5]
        try:
            c = json.load(open(fpath, encoding='utf-8'))
        except Exception as e:
            problems.append(f'{f}: not valid JSON ({e})')
            continue
        c['name'] = name
        for i, s in enumerate(c.get('shots', [])):
            if s.get('layer') not in layer_names:
                problems.append(f"{f}: shot {i + 1} uses unknown layer {s.get('layer')!r} (known: {', '.join(sorted(layer_names))})")
            for k in (s.get('params') or {}).get('layers') or []:
                if k.get('layer') not in layer_names:
                    problems.append(f"{f}: shot {i + 1} stacks unknown layer {k.get('layer')!r}")
        if name in carts:
            problems.append(f'{f}: another cartridge is also called {name!r}')
        carts[name] = c
    if problems:
        print('Problems (fix these, then run again):')
        for p in problems:
            print('  -', p)
        sys.exit(1)
    if not carts:
        sys.exit('No cartridges found in ' + carts_dir)

    write_knobs_md()

    bundle = ('/* GENERATED by gen/build.py from carts/*.json. Do not edit by hand; edit the JSON files. */\n'
              'GEN.CARTS = ' + json.dumps(carts, indent=1, ensure_ascii=False) + ';\n')
    open(os.path.join(carts_dir, '_bundle.js'), 'w', encoding='utf-8').write(bundle)
    print(f'carts/_bundle.js: {len(carts)} cartridges ({", ".join(carts)})')

    # the built file can hold fewer cartridges than the folder bundle (which always has them all)
    out_name, default_cart, page_title, n_all = OUT_NAME, DEFAULT_CART, PAGE_TITLE, len(carts)
    if only_cart:
        if only_cart not in carts:
            sys.exit(f'ONLY_CART {only_cart!r} not found (cartridges: {", ".join(carts)})')
        c = carts[only_cart]
        carts = {only_cart: c}
        out_name, default_cart = only_cart + '.html', only_cart
        page_title = ' · '.join(x for x in (c.get('title'), c.get('subtitle')) if x) or only_cart
        print(f'STANDALONE: only {only_cart!r}')
    elif ONLY_CARTS:
        carts = {k: v for k, v in carts.items() if k in ONLY_CARTS}
    if len(carts) < n_all:
        bundle = ('/* GENERATED by gen/build.py */\n'
                  'GEN.CARTS = ' + json.dumps(carts, indent=1, ensure_ascii=False) + ';\n')

    html = open(os.path.join(GEN_DIR, 'player.html'), encoding='utf-8').read()

    # audio tracks named by cartridges ("audio": "file.mp3"), embedded as data URLs
    audio = {}
    for c in carts.values():
        a = c.get('audio')
        if not a or a in audio:
            continue
        ap = os.path.join(AUDIO_DIR, a)
        if not os.path.exists(ap):
            print(f"Note: {c['name']} wants audio {a!r}, not found in {AUDIO_DIR} (drop the file on the player instead)")
        elif EMBED_AUDIO:
            mime = {'.mp3': 'audio/mpeg', '.m4a': 'audio/mp4', '.aac': 'audio/aac', '.wav': 'audio/wav', '.ogg': 'audio/ogg', '.flac': 'audio/flac'}.get(os.path.splitext(a)[1].lower(), 'audio/mpeg')
            audio[a] = f'data:{mime};base64,' + base64.b64encode(open(ap, 'rb').read()).decode('ascii')
            print(f'Embedded audio: {a} ({len(audio[a]) // 1024} KB as base64)')

    def inline(m):
        rel = m.group(1)
        if rel == 'carts/_bundle.js':
            code = bundle
            if default_cart in carts:
                code += f'GEN.CARTS = Object.assign({{ {json.dumps(default_cart)}: GEN.CARTS[{json.dumps(default_cart)}] }}, GEN.CARTS);\n'
            if audio:
                code += 'GEN.AUDIO = ' + json.dumps(audio) + ';\n'
            if only_cart:
                code += 'GEN.PRESENT = true;\n'   # standalone = presentation mode: no gallery, knobs or cartridge menu
        else:
            code = open(os.path.join(GEN_DIR, rel), encoding='utf-8').read()
        code = code.replace('</script', '<\\/script')
        return f'<script>/* {rel} */\n{code}\n</script>'

    out, n = re.subn(r'<script src="([^"]+)"></script>', inline, html)
    out = out.replace('<title>Gen Player</title>', f'<title>{page_title}</title>')
    faces = []
    for family, path in (('GenMono', FONT_FILE), ('GenDisplay', DISPLAY_FONT)):
        if not path:
            continue
        ext = os.path.splitext(path)[1].lower().lstrip('.')
        fmt = {'woff2': 'woff2', 'woff': 'woff', 'ttf': 'truetype', 'otf': 'opentype'}.get(ext)
        if not fmt:
            sys.exit(f'{path}: fonts must be .woff2, .woff, .ttf or .otf')
        b64 = base64.b64encode(open(path, 'rb').read()).decode('ascii')
        mime = {'woff2': 'font/woff2', 'woff': 'font/woff', 'truetype': 'font/ttf', 'opentype': 'font/otf'}[fmt]
        faces.append(f"@font-face {{ font-family: {family}; src: url(data:{mime};base64,{b64}) format('{fmt}'); font-display: block; }}")
        print(f'Embedded font {family}:', os.path.basename(path), f'({len(b64) // 1024} KB as base64)')
    out = out.replace('/*__FONTFACE__*/', '\n'.join(faces))
    if re.search(r'<script src=|<link[^>]+href="http|url\(http', out):
        sys.exit('Build still references an outside file; not writing it.')

    path = out_path or os.path.join(OUT_DIR, out_name)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'w', encoding='utf-8').write(out)
    print(f'Wrote {path}  ({len(out) // 1024} KB, {n} scripts inlined)')
    return path

def write_knobs_md():
    """KNOBS.md: every layer's knobs (default, min, max, step, comment), read from layers/*.js.
    Generated so it can never drift from the code; a cheap file for Claude to read instead of the sources."""
    def helps(src, key):
        m = re.search(key + r'\s*=?\s*:?\s*\{(.*?)\n\s*\};?', src, re.S)
        return {k: json.loads(v) for k, v in re.findall(r'^\s*(\w+):\s*("(?:[^"\\]|\\.)*")', m.group(1), re.M)} if m else {}
    common = helps(open(os.path.join(GEN_DIR, 'stage.js'), encoding='utf-8').read(), r'G\.knobHelp')
    out = ['# Layer knobs (GENERATED by gen/build.py from layers/*.js; do not edit)', '',
           'Format: `name: default` [min to max, step]. Put only the knobs you change in a shot\'s `params`.', '']
    for f in sorted(os.listdir(os.path.join(GEN_DIR, 'layers'))):
        if not f.endswith('.js'):
            continue
        src = open(os.path.join(GEN_DIR, 'layers', f), encoding='utf-8').read()
        name = re.search(r'G\.layers\.(\w+)\s*=', src)
        about = re.search(r"about:\s*'([^']*)'", src)
        block = re.search(r'knobs:\s*\{(.*?)\n\s*\},', src, re.S)
        if not (name and block):
            continue
        own = helps(src, r'\bhelp')
        warm = re.search(r'warm:\s*([\d.]+)', src)
        out.append(f'## {name.group(1)}  (`layers/{f}`)' + ('  · stateful, warm-up ' + warm.group(1) + ' s' if warm else ''))
        if about:
            out.append(about.group(1))
        out.append('')
        for line in block.group(1).splitlines():
            m = re.match(r"\s*(\w+):\s*(\[[^\]]*\]|\{[^}]*\}|[^,]+),?\s*(?://\s*(.*))?$", line)
            if not m:
                continue
            k, spec = m.group(1), m.group(2)
            note = own.get(k) or common.get(k) or (m.group(3) or '').strip()
            nums = re.fullmatch(r'\[\s*([-\d.e]+)\s*,\s*([-\d.e]+)\s*,\s*([-\d.e]+)\s*,\s*([-\d.e]+)\s*\]', spec)
            desc = f'`{k}: {nums.group(1)}` [{nums.group(2)} to {nums.group(3)}, step {nums.group(4)}]' if nums else f'`{k}: {spec}`'
            out.append('- ' + desc + (f'  {note}' if note else ''))
        out.append('')
    m3d = open(os.path.join(GEN_DIR, 'm3d.js'), encoding='utf-8').read()
    shapes = re.findall(r'^\s{4}(\w+): \{ wrapU', m3d, re.M)
    out.append('## depth shapes (`m3d.js`)')
    out.append(', '.join(f'`{s}`' for s in shapes))
    out.append('')
    open(os.path.join(GEN_DIR, 'KNOBS.md'), 'w', encoding='utf-8').write('\n'.join(out))
    print('KNOBS.md written')

if __name__ == '__main__':
    main()
